export type WeekDecks = [Card[], Card[], Card[]]

export function makeDecks(): WeekDecks {
  let id = 0
  const create = (values: [number, number][]): Card[] =>
    values.map(([top, bottom]) => ({ id: ++id, top, bottom }))
  return [create(WEEK_1), create(WEEK_2), create(WEEK_3)]
}
